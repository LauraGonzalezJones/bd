CREATE TABLE  ES PARA CREAR UNA TABLA NUEVA EN LA BASE DE DATOS

id es para identificar de manera única cada registro en la tabla, generalmente es una clave primaria.

having es una cláusula que se utiliza en conjunto con GROUP BY para filtrar los resultados agregados.

sum es una función de agregación que se utiliza para calcular la suma de un conjunto de valores.

left join es un tipo de unión que devuelve todos los registros de la tabla de la izquierda y los registros coincidentes de la tabla de la derecha.
select es una palabra clave utilizada para iniciar una consulta SQL y especificar las columnas que se desean recuperar de una tabla.

where es una cláusula que se utiliza para filtrar los registros de una tabla según una condición específica.    
 
